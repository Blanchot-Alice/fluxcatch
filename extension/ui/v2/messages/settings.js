// holds no Latin words. Display strings are listed in `display`.
import { formatCount, plural, uiLocale } from "../locale.js";

const list = (items) => {
  const values = (Array.isArray(items) ? items : []).map((item) => String(item ?? ""));
  try { return new Intl.ListFormat(uiLocale(), { style: "long", type: "conjunction" }).format(values); } catch { return values.join(", "); }
};
const text = (value) => String(value ?? "");
// Site names arrive as an array. English joins them as a list ("Instagram and X");
// Chinese uses the approved "Instagram 与 X", spaced like the rest of the line.
const sitesEn = (sites) => (Array.isArray(sites) ? list(sites) : text(sites));
const sitesZh = (sites) => (Array.isArray(sites) ? sites.map(text).join(" 与 ") : text(sites));
// A status word may end in an ellipsis ("Checking…"); the announcement adds its own stop.
const bare = (value) => text(value).replace(/…$/, "");

